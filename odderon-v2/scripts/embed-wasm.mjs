/* Embed src/core/odderon-core.wasm as a base64 TypeScript module.
 *
 * The game has to load from a file:// URL inside Electron, where fetch() is
 * not allowed for local files, so the module travels inside the bundle
 * instead of beside it.
 */

import { readFile, writeFile } from "node:fs/promises";

const src = new URL("../src/core/odderon-core.wasm", import.meta.url);
const out = new URL("../src/core/core-bytes.ts", import.meta.url);

let bytes;
try {
  bytes = await readFile(src);
} catch {
  console.warn("embed-wasm: src/core/odderon-core.wasm is missing; the bridge will fall back to TypeScript");
  bytes = new Uint8Array(0);
}

const base64 = Buffer.from(bytes).toString("base64");
const lines = base64.match(/.{1,96}/g) ?? [];
const body = [
  "/* Generated by scripts/embed-wasm.mjs. Do not edit.",
  " * Source: odderon-v2/rust, built by .github/workflows/odderon-v2-core.yml.",
  " */",
  "",
  `export const CORE_WASM_BASE64 =`,
  ...lines.map((l, i) => `  "${l}"${i === lines.length - 1 ? ";" : " +"}`),
  "",
  `export const CORE_WASM_BYTES = ${bytes.byteLength};`,
  "",
].join("\n");
await writeFile(out, body);
console.log(`embed-wasm: ${bytes.byteLength} bytes -> src/core/core-bytes.ts (${base64.length} base64 chars)`);
