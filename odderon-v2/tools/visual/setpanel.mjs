import chromium from "@sparticuz/chromium";
import { chromium as pw } from "playwright-core";
const browser = await pw.launch({ executablePath: "/tmp/chromium", args: [...chromium.args,"--use-gl=angle","--use-angle=swiftshader","--enable-unsafe-swiftshader","--in-process-gpu"], headless: true, timeout: 90000 });
const page = await browser.newPage({ viewport: { width: 1600, height: 900 } });
const errors = [];
page.on("pageerror", e => errors.push(e.message.slice(0,200)));
await page.goto("http://127.0.0.1:5173/", { waitUntil: "load" });
await page.waitForTimeout(2200);
await page.click('[data-action="settings"]');
await page.waitForTimeout(700);
await page.screenshot({ path: "tools/visual/.shots/p-settings.png" });
console.log({ core: await page.textContent("#set-core"), renderer: await page.textContent("#set-renderer"), errors });
await browser.close();
